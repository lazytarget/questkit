"""`quest completion` — print a shell completion script (the `gh completion`
convention: the user `eval`s it from their shell rc).

Static completion (subcommand names, per-subcommand flags) is introspected
from the real `argparse` parser `cli.build_parser()` builds, so the
completions can never drift from the CLI they describe -- a hand-maintained
flag list would. Dynamic completion (quest ids, `--in` project names,
`--where`/`--select`/`--sort` field names) is delegated *inside the
generated script* back to `quest` itself:

- ids: ``quest list --format csv --select id --quiet`` -- deliberately no
  ``-A``, so completion only ever resolves the nearest log and stays fast.
- project names: ``quest logs --format json``
- field names: ``quest schema quest --format json`` (`fields` + `core_fields`)

The script reads the actually-typed program name from ``COMP_WORDS[0]`` /
``$argv[1]`` / the fish ``commandline`` builtin rather than hardcoding
``quest``, so registering it for both ``quest`` and ``qst`` (its alias)
gets identical behavior under either name for free.
"""

from __future__ import annotations

import argparse


def _subparsers_action(parser: argparse.ArgumentParser) -> argparse._SubParsersAction:
    group = parser._subparsers
    assert group is not None
    return next(a for a in group._group_actions if isinstance(a, argparse._SubParsersAction))


def _subcommands_and_flags() -> dict[str, list[str]]:
    """{subcommand: [flag strings]}, introspected from the built parser --
    imported lazily to avoid a cycle (`cli` imports every `commands.*`
    module, including this one, to wire up subparsers)."""
    from ..cli import build_parser

    parser = build_parser()
    action = _subparsers_action(parser)
    result: dict[str, list[str]] = {}
    for name, subparser in action.choices.items():
        flags: list[str] = []
        for sub_action in subparser._actions:
            flags.extend(sub_action.option_strings)
        result[name] = sorted(flags)
    return result


# Subcommands whose second word (`quest <sub> <id>`) is a quest id -- these
# are the ones that resolve like `show` (see `resolve_mutation_target`).
_ID_SUBCOMMANDS = (
    "show", "edit", "open", "set", "done", "scrap",
    "archive", "unarchive", "mv", "deps", "brief",
)

# Subcommands whose --in/--root take a project name or log path rather than
# a bare flag value -- everything that shares `_add_list_options`, plus the
# single-log commands that also accept --in.
_IN_TAKING_SUBCOMMANDS = (
    "list", "next", "stale", "blocked", "show", "edit", "open", "new",
    "set", "done", "scrap", "archive", "unarchive", "mv", "brief", "deps",
    "logs", "migrate", "commit", "schema", "validate", "format",
)

# Flags whose value is a schema field name.
_FIELD_TAKING_FLAGS = ("--where", "--any", "--select", "--sort", "--group-by")


def bash_script() -> str:
    flags = _subcommands_and_flags()
    subcommands = " ".join(sorted(flags))
    id_subs = " ".join(_ID_SUBCOMMANDS)
    flag_cases = "\n".join(
        f'        {name}) flags="{" ".join(f)}" ;;' for name, f in sorted(flags.items())
    )
    return f"""\
# bash completion for quest/qst -- generated by `quest completion bash`.
# Install: eval "$(quest completion bash)"   (add to ~/.bashrc)
_quest_complete() {{
    local cur prev prog sub
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    prog="${{COMP_WORDS[0]}}"
    sub="${{COMP_WORDS[1]}}"

    if [[ $COMP_CWORD -eq 1 ]]; then
        COMPREPLY=( $(compgen -W "{subcommands}" -- "$cur") )
        return 0
    fi

    case "$prev" in
        --in)
            COMPREPLY=( $(compgen -W "$(_quest_complete_projects "$prog")" -- "$cur") )
            return 0
            ;;
        {"|".join(_FIELD_TAKING_FLAGS)})
            COMPREPLY=( $(compgen -W "$(_quest_complete_fields "$prog")" -- "$cur") )
            return 0
            ;;
    esac

    case " {id_subs} " in
        *" $sub "*)
            if [[ $COMP_CWORD -eq 2 ]]; then
                COMPREPLY=( $(compgen -W "$(_quest_complete_ids "$prog")" -- "$cur") )
                return 0
            fi
            ;;
    esac

    local flags=""
    case "$sub" in
{flag_cases}
    esac
    COMPREPLY=( $(compgen -W "$flags" -- "$cur") )
}}

# Fast: no -A sweep, so only the nearest log resolves.
_quest_complete_ids() {{
    "$1" list --format csv --select id --quiet 2>/dev/null | tail -n +2
}}

_quest_complete_projects() {{
    "$1" logs --format json 2>/dev/null | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    data = []
for entry in data:
    if entry.get("project"):
        print(entry["project"])
' 2>/dev/null
}}

_quest_complete_fields() {{
    "$1" schema quest --format json 2>/dev/null | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    data = {{}}
names = set(data.get("fields", {{}}).keys()) | set(data.get("core_fields", {{}}).keys())
for name in sorted(names):
    print(name)
' 2>/dev/null
}}

complete -F _quest_complete quest qst
"""


def zsh_script() -> str:
    flags = _subcommands_and_flags()
    subcommand_descs = " ".join(f"{name}" for name in sorted(flags))
    flag_cases = "\n".join(
        f'            {name}) flags=({" ".join(f)}) ;;' for name, f in sorted(flags.items())
    )
    id_subs = " ".join(_ID_SUBCOMMANDS)
    return f"""\
#compdef quest qst
# zsh completion for quest/qst -- generated by `quest completion zsh`.
# Install: eval "$(quest completion zsh)"   (add to ~/.zshrc, after compinit)

_quest_complete_ids() {{ "$1" list --format csv --select id --quiet 2>/dev/null | tail -n +2 }}
_quest_complete_projects() {{
    "$1" logs --format json 2>/dev/null | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    data = []
for entry in data:
    if entry.get("project"):
        print(entry["project"])
' 2>/dev/null
}}
_quest_complete_fields() {{
    "$1" schema quest --format json 2>/dev/null | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    data = {{}}
names = set(data.get("fields", {{}}).keys()) | set(data.get("core_fields", {{}}).keys())
for name in sorted(names):
    print(name)
' 2>/dev/null
}}

_quest() {{
    local prog="${{words[1]}}"
    local curcontext="$curcontext" state line
    local -a subcommands
    subcommands=({subcommand_descs})

    if (( CURRENT == 2 )); then
        _describe 'command' subcommands
        return
    fi

    local sub="${{words[2]}}"
    case "${{words[-2]}}" in
        --in)
            local -a projects
            projects=(${{(f)"$(_quest_complete_projects "$prog")"}})
            _describe 'project' projects
            return
            ;;
        {"|".join(_FIELD_TAKING_FLAGS)})
            local -a fields
            fields=(${{(f)"$(_quest_complete_fields "$prog")"}})
            _describe 'field' fields
            return
            ;;
    esac

    case " {id_subs} " in
        *" $sub "*)
            if (( CURRENT == 3 )); then
                local -a ids
                ids=(${{(f)"$(_quest_complete_ids "$prog")"}})
                _describe 'quest id' ids
                return
            fi
            ;;
    esac

    local -a flags
    case "$sub" in
{flag_cases}
    esac
    _describe 'flag' flags
}}

compdef _quest quest qst
"""


def fish_script() -> str:
    flags = _subcommands_and_flags()
    lines: list[str] = [
        "# fish completion for quest/qst -- generated by `quest completion fish`.",
        "# Install: quest completion fish | source   (add to ~/.config/fish/config.fish)",
        "",
        "function __quest_complete_ids",
        "    $argv[1] list --format csv --select id --quiet 2>/dev/null | tail -n +2",
        "end",
        "function __quest_complete_projects",
        "    $argv[1] logs --format json 2>/dev/null | python3 -c '",
        "import json, sys",
        "try:",
        "    data = json.load(sys.stdin)",
        "except Exception:",
        "    data = []",
        "for entry in data:",
        "    if entry.get(\"project\"):",
        "        print(entry[\"project\"])",
        "' 2>/dev/null",
        "end",
        "function __quest_complete_fields",
        "    $argv[1] schema quest --format json 2>/dev/null | python3 -c '",
        "import json, sys",
        "try:",
        "    data = json.load(sys.stdin)",
        "except Exception:",
        "    data = {}",
        "names = set(data.get(\"fields\", {}).keys()) | set(data.get(\"core_fields\", {}).keys())",
        "for name in sorted(names):",
        "    print(name)",
        "' 2>/dev/null",
        "end",
        "function __quest_prev_arg_is",
        "    set -l tokens (commandline -opc)",
        "    test (count $tokens) -ge 1; and test \"$tokens[-1]\" = \"$argv[1]\"",
        "end",
        "",
    ]
    for prog in ("quest", "qst"):
        lines.append(f"complete -c {prog} -f")
        for name in sorted(flags):
            lines.append(
                f"complete -c {prog} -n '__fish_use_subcommand' -a {name}"
            )
        for name in _ID_SUBCOMMANDS:
            lines.append(
                f"complete -c {prog} -n '__fish_seen_subcommand_from {name}' "
                f"-a '(__quest_complete_ids {prog})'"
            )
        lines.append(
            f"complete -c {prog} -n '__quest_prev_arg_is --in' "
            f"-a '(__quest_complete_projects {prog})'"
        )
        for flag in _FIELD_TAKING_FLAGS:
            lines.append(
                f"complete -c {prog} -n \"__quest_prev_arg_is {flag}\" "
                f"-a '(__quest_complete_fields {prog})'"
            )
        for name, flag_list in sorted(flags.items()):
            for flag in flag_list:
                lines.append(
                    f"complete -c {prog} -n '__fish_seen_subcommand_from {name}' "
                    f"-l {flag.lstrip('-')}"
                )
    return "\n".join(lines) + "\n"


_GENERATORS = {"bash": bash_script, "zsh": zsh_script, "fish": fish_script}


def run(args: argparse.Namespace) -> int:
    print(_GENERATORS[args.shell](), end="")
    return 0
